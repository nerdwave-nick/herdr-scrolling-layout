// Command herdr-scrolling-layout is a Herdr plugin that brings niri-style
// keyboard navigation to Herdr: workspaces stack vertically, the tabs of a
// workspace form a horizontal strip, and panes are windows inside a tab.
//
// Herdr runs one subcommand per key press (see herdr-plugin.toml):
//
//	focus left|right|up|down
//	move  left|right|up|down
//	maximize-column
//	fullscreen-window
//
// `keys` prints keybinding config for ~/.config/herdr/config.toml.
package main

import (
	"context"
	"flag"
	"fmt"
	"os"
	"strings"
	"time"

	herdr "github.com/nerdwave-nick/herdr-go"
	"github.com/nerdwave-nick/herdr-scrolling-layout/internal/config"
	"github.com/nerdwave-nick/herdr-scrolling-layout/internal/layout"
	"github.com/nerdwave-nick/herdr-scrolling-layout/internal/nav"
	"github.com/nerdwave-nick/herdr-scrolling-layout/internal/state"
)

// PluginID must match id in herdr-plugin.toml.
const PluginID = "herdr-scrolling-layout"

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "herdr-scrolling-layout:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	if len(args) == 0 {
		return usage()
	}
	switch args[0] {
	case "keys":
		return keys(args[1:])
	case "focus", "move":
		if len(args) != 2 {
			return usage()
		}
		d, ok := layout.ParseDir(args[1])
		if !ok {
			return fmt.Errorf("unknown direction %q", args[1])
		}
		return act(func(ctx context.Context, n *nav.Nav) error {
			if args[0] == "focus" {
				return n.Focus(ctx, d)
			}
			return n.Move(ctx, d)
		})
	case "maximize-column":
		return act(func(ctx context.Context, n *nav.Nav) error { return n.MaximizeColumn(ctx) })
	case "fullscreen-window":
		return act(func(ctx context.Context, n *nav.Nav) error { return n.FullscreenWindow(ctx) })
	}
	return usage()
}

func act(fn func(context.Context, *nav.Nav) error) error {
	c, err := herdr.FromEnv()
	if err != nil {
		return err
	}
	cfg, err := config.Load()
	if err != nil {
		return err
	}
	st, err := state.Open()
	if err != nil {
		return err
	}
	defer st.Close()
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	n := &nav.Nav{C: c, Cfg: cfg, State: st, PaneID: nav.FromEnv()}
	actErr := fn(ctx, n)
	// Save even on error: earlier steps may have changed what we track.
	if err := st.Save(); err != nil && actErr == nil {
		actErr = err
	}
	return actErr
}

func usage() error {
	return fmt.Errorf(`usage:
  herdr-scrolling-layout focus|move left|right|up|down
  herdr-scrolling-layout maximize-column|fullscreen-window
  herdr-scrolling-layout keys [-mod alt] [-keys h,j,k,l]`)
}

// keys prints [[keys.command]] bindings for config.toml.
func keys(args []string) error {
	fs := flag.NewFlagSet("keys", flag.ContinueOnError)
	mod := fs.String("mod", "alt", `modifier for all bindings, e.g. "alt", "ctrl+alt", or "prefix" for prefix+key`)
	dirKeys := fs.String("keys", "h,j,k,l", "keys for left,down,up,right")
	full := fs.String("fullscreen", "f", "key for maximize-column (shift+key toggles fullscreen-window)")
	if err := fs.Parse(args); err != nil {
		return err
	}
	ks := strings.Split(*dirKeys, ",")
	if len(ks) != 4 {
		return fmt.Errorf("-keys needs four comma-separated keys for left,down,up,right")
	}
	chord := func(shift bool, key string) string {
		m := strings.TrimSuffix(*mod, "+")
		if shift {
			m += "+shift"
		}
		return m + "+" + key
	}
	dirs := []string{"left", "down", "up", "right"}
	fmt.Printf("# herdr-scrolling-layout keybindings (generated by `herdr-scrolling-layout keys -mod %s`)\n", *mod)
	emit := func(key, action, desc string) {
		fmt.Printf("\n[[keys.command]]\nkey = %q\ntype = \"plugin_action\"\ncommand = \"%s.%s\"\ndescription = %q\n", key, PluginID, action, desc)
	}
	for i, d := range dirs {
		emit(chord(false, ks[i]), "focus-"+d, "focus "+d+" (crosses tabs/workspaces)")
	}
	for i, d := range dirs {
		emit(chord(true, ks[i]), "move-"+d, "move window "+d+" (crosses tabs/workspaces)")
	}
	emit(chord(false, *full), "maximize-column", "toggle maximize column")
	emit(chord(true, *full), "fullscreen-window", "toggle fullscreen window")
	return nil
}
